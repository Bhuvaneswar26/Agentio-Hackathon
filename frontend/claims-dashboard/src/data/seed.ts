function lines(items: Array<Partial<InvoiceLine> & { description: string; amount: number }>, provider: string, invoice: string, date: string): InvoiceLine[] {
  return items.map((item, i) => ({
    id: `${invoice}-L${i + 1}`,
    code: item.code ?? `CPT-${800 + i}`,
    quantity: item.quantity ?? 1,
    unitPrice: item.unitPrice ?? item.amount,
    amount: item.amount,
    provider,
    invoiceRef: invoice,
    date,
    description: item.description,
  }))
}

function finding(partial: Omit<Finding, 'id'> & { id?: string }): Finding {
  return { id: partial.id ?? `F-${Math.random().toString(36).slice(2, 7)}`, ...partial }
}

