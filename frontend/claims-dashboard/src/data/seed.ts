function extraClaims(): Claim[] {
  const out: Claim[] = []
  for (let i = 0; i < 28; i += 1) {
    const domain: Claim['domain'] = i % 3 === 0 ? 'Health' : i % 3 === 1 ? 'Motor' : 'General'
    const flagged = i % 4 === 0
    const good = i % 5 === 0 && !flagged
    const amount = 8000 + i * 3750
    const leakage = flagged ? Math.round(amount * 0.18) : 0
    const provider = extraProviders[i % extraProviders.length]
    const id = `CLM-31${(100 + i).toString()}`
    const queue: Claim['queue'] = flagged ? 'flagged' : good ? 'good' : i % 7 === 0 ? 'intake' : 'good'
    out.push({
      id,
      policyNumber: `${domain.slice(0, 2).toUpperCase()}-${4000 + i}`,
      claimant: ['Aditi Rao', 'Vikram Sethi', 'Neelima Das', 'Harsh Vardhan', 'Leela Krishnan'][i % 5],
      incidentDate: `2026-${String((i % 9) + 1).padStart(2, '0')}-${String((i % 27) + 1).padStart(2, '0')}`,
      filedDate: `2026-${String((i % 9) + 1).padStart(2, '0')}-${String(Math.min((i % 27) + 2, 28)).padStart(2, '0')}`,
      domain,
      claimType: domain === 'Health' ? 'OPD' : domain === 'Motor' ? 'Own damage' : 'Fire',
      requestedAmount: amount,
      proposedSettlement: amount,
      expectedSettlement: amount - leakage,
      confirmedLeakage: flagged && i % 8 === 0 ? leakage : 0,
      potentialLeakage: flagged && i % 8 !== 0 ? leakage : 0,
      provider,
      city: ['Mumbai', 'Jaipur', 'Lucknow', 'Indore', 'Nagpur'][i % 5],
      queue,
      riskScore: flagged ? 55 + (i % 30) : 8 + (i % 15),
      sourceFormat: (['json', 'csv', 'pdf', 'xlsx'] as const)[i % 4],
      extractionConfidence: 0.7 + (i % 20) / 100,
      missingFields: [],
      relatedClaimIds: [],
      notes: '',
      lines: lines([{ description: 'Package line', amount }], provider, `INV-X-${i}`, '2026-09-01'),
      policyRules: domain === 'Health' ? healthRules(4000, 5000, 10) : [{ id: 'STD', name: 'Standard cover', clause: 'Standard coverage applies.', type: 'coverage' }],
      findings: flagged
        ? [
            finding({
              kind: i % 2 === 0 ? 'provider_anomaly' : 'settlement_error',
              title: i % 2 === 0 ? 'Billing above peer band' : 'Copay missed on proposed payout',
              explanation: 'Synthetic portfolio example for ratio dashboards.',
              evidence: ['Peer benchmark'],
              invoiceLineIds: [],
              certainty: i % 8 === 0 ? 'confirmed' : 'potential',
              severity: leakage > 12000 ? 'high' : 'medium',
              leakageAmount: leakage,
              engine: i % 2 === 0 ? 'ml' : 'rules',
            }),
          ]
        : [],
    })
  }
  return out
}

